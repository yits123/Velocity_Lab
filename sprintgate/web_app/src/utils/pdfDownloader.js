// Universal fail-safe PDF file downloader supporting mobile & desktop browsers
export const savePdfFile = (doc, filename) => {
  try {
    doc.save(filename);
  } catch (err) {
    console.warn("doc.save failed, falling back to Blob download:", err);
    try {
      const blob = doc.output('blob');
      const blobUrl = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = blobUrl;
      a.download = filename;
      document.body.appendChild(a);
      a.click();
      setTimeout(() => {
        if (a.parentNode) document.body.removeChild(a);
        URL.revokeObjectURL(blobUrl);
      }, 150);
    } catch (fallbackErr) {
      console.error("PDF download completely failed:", fallbackErr);
    }
  }
};
